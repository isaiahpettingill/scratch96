import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tinyccDir = join(root, "vendor", "tinycc");
const generatedDir = join(root, "build", "tcc-wasm", "generated");
const wasmDir = join(root, "public", "wasm");
const wrapperPath = join(root, "tools", "tcc-wasm", "tcc_wasm_wrapper.c");
const wasmPath = join(wasmDir, "tcc-wasm.wasm");
const loaderPath = join(wasmDir, "tcc-wasm.js");
const manifestPath = join(wasmDir, "tcc-wasm.manifest.json");

await mkdir(generatedDir, { recursive: true });
await mkdir(wasmDir, { recursive: true });
await writeFile(join(generatedDir, "config.h"), tccConfigHeader());

const emcc = process.env.EMCC ?? "emcc";
const emccVersion = (commandOutput(emcc, ["--version"]).split("\n")[0] ?? emcc).trim();
const upstreamCommit = commandOutput("git", ["-C", tinyccDir, "rev-parse", "HEAD"]);
const args = [
  join(tinyccDir, "libtcc.c"),
  wrapperPath,
  "-o",
  loaderPath,
  "-I",
  generatedDir,
  "-I",
  tinyccDir,
  "-DONE_SOURCE=1",
  "-DCONFIG_TCC_STATIC=1",
  "-DTCC_TARGET_RISCV64=1",
  "-DTCC_GITHASH=\"scratch96\"",
  "-O2",
  "-fno-strict-aliasing",
  "-Wno-pointer-sign",
  "-Wno-sign-compare",
  "-Wno-unused-result",
  "-sMODULARIZE=1",
  "-sEXPORT_ES6=1",
  "-sENVIRONMENT=web,worker",
  "-sALLOW_MEMORY_GROWTH=1",
  "-sINITIAL_MEMORY=67108864",
  "-sSTACK_SIZE=1048576",
  "-sFORCE_FILESYSTEM=1",
  "-sEXPORTED_FUNCTIONS=['_compile_program','_link_assembly','_allocUint8','_freeUint8','_last_error','_malloc','_free']",
  "-sEXPORTED_RUNTIME_METHODS=['HEAPU8']",
  "--embed-file",
  `${join(tinyccDir, "include")}@/include`,
];

run(emcc, args);

const wasmBytes = await readFile(wasmPath);
const loaderBytes = await readFile(loaderPath);
const sha256 = createHash("sha256").update(wasmBytes).digest("hex");
const loaderSha256 = createHash("sha256").update(loaderBytes).digest("hex");
await writeFile(
  manifestPath,
  `${JSON.stringify(
    {
      name: "tinycc-wasm",
      upstream: "https://github.com/TinyCC/tinycc",
      upstreamCommit,
      artifact: "tcc-wasm.wasm",
      loader: "tcc-wasm.js",
      sha256,
      loaderSha256,
      target: "wasm32-emscripten",
      exports: ["compile_program", "link_assembly", "allocUint8"],
      buildToolchain: { emcc: emccVersion },
    },
    null,
    2,
  )}\n`,
);

console.log(`wrote ${wasmPath}`);
console.log(`wrote ${loaderPath}`);
console.log(`wrote ${manifestPath}`);

function tccConfigHeader() {
  return `/* Generated by scripts/build-tcc-wasm.mjs. */

#define TCC_VERSION "0.9.27-scratch96"
#define CC_NAME CC_gcc
#define GCC_MAJOR 0
#define GCC_MINOR 0
#define TCC_TARGET_RISCV64 1
#define CONFIG_TCC_PREDEFS 0
#define CONFIG_TCC_BACKTRACE 0
#define CONFIG_TCC_BCHECK 0
#define CONFIG_TCC_SEMLOCK 0
#define CONFIG_TCCDIR "/"
#define CONFIG_TCC_CROSSPREFIX ""
#define CONFIG_TCC_CRTPREFIX "/"
#define CONFIG_TCC_LIBPATHS "{B}"
#define CONFIG_TCC_SYSINCLUDEPATHS "{B}/include"
#define CONFIG_TCC_ELFINTERP "/lib/ld-linux-riscv64-lp64d.so.1"
`;
}

function commandOutput(command, args) {
  const result = spawnSync(command, args, { cwd: root, encoding: "utf8" });
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(" ")} failed:\n${result.stderr || result.stdout}`);
  }
  return result.stdout.trim();
}

function run(command, args) {
  const result = spawnSync(command, args, { cwd: root, encoding: "utf8", stdio: "inherit" });
  if (result.status !== 0) throw new Error(`${command} failed with exit code ${result.status}`);
}
